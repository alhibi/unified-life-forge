export type ChessPaletteKey = keyof typeof CHESS_PALETTE;

const HEX_RE = /^[0-9a-fA-F]{6}$/;

/** يتحقق أن كل قيمة في اللوحة سداسي صالح بلا «#». يُستدعى في الاختبارات. */
export function assertPaletteIntegrity(): { ok: boolean; badKeys: ChessPaletteKey[] } {
  const badKeys: ChessPaletteKey[] = [];
  (Object.keys(CHESS_PALETTE) as ChessPaletteKey[]).forEach((k) => {
    if (!HEX_RE.test(CHESS_PALETTE[k])) badKeys.push(k);
  });
  return { ok: badKeys.length === 0, badKeys };
}

/** يحول إدخال اللوحة إلى THREE.Color بأمان الأنواع. */
export function paletteColor(key: ChessPaletteKey): string {
  return `#${CHESS_PALETTE[key]}`;
}

