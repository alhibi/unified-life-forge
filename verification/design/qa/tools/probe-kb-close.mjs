import { chromium } from '@playwright/test';
import fs from 'node:fs';
const OUT='verification/design/qa/shared-layer/interactions';
const PROFILE={'app-theme':'dark','app-color-theme':'expressive','app-palette-style':'tonal','app-black-mode':'false','app-surface-lift':'subtle','app-ui-density':'cozy','app-content-width':'standard','app-reduced-motion':'true'};
const browser=await chromium.launch();
const ctx=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,locale:'ar',timezoneId:'Asia/Riyadh',reducedMotion:'reduce',colorScheme:'dark'});
await ctx.addInitScript((p)=>{for(const[k,v]of Object.entries(p))localStorage.setItem(k,v)},PROFILE);
const page=await ctx.newPage();
await page.route('**/*',(r)=>{const h=new URL(r.request().url()).hostname;if(h==='127.0.0.1'||h==='localhost'||h.endsWith('googleapis.com')||h.endsWith('gstatic.com'))return r.continue();return r.abort();});
await page.goto('http://127.0.0.1:5199/settings/keyboard',{waitUntil:'domcontentloaded'});await page.waitForTimeout(2200);
const snap=()=>page.evaluate(()=>({attr:document.documentElement.getAttribute('data-soft-keyboard-open'),height:getComputedStyle(document.documentElement).getPropertyValue('--soft-keyboard-height'),panel:!!document.querySelector('[data-soft-keyboard-panel]'),panelButtons:[...document.querySelectorAll('[data-soft-keyboard-panel] button')].map(b=>b.getAttribute('aria-label')).filter(Boolean).slice(0,6),labels:[...document.querySelectorAll('button')].map(b=>b.getAttribute('aria-label')).filter(l=>l&&/لوحة المفاتيح/.test(l))}));
const before=await snap();
await page.locator('button[aria-label="فتح لوحة المفاتيح للتجربة"]').first().click();await page.waitForTimeout(1000);
const opened=await snap();
await page.locator('button[aria-label="إغلاق لوحة المفاتيح"]').first().click();await page.waitForTimeout(500);
const close500=await snap();
await page.waitForTimeout(1200);
const close1700=await snap();
await page.screenshot({path:OUT+'/keyboard-after-close.png',animations:'disabled'});
console.log(JSON.stringify({before,opened,close500,close1700},null,1));
await ctx.close();await browser.close();
